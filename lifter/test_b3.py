"""[witchtime] Check the SIMD forms added for Bayonetta 3 (lifter/recomp.py, marked [witchtime]) against Unicorn.

Finds every instruction of the player's own main.elf whose lifted statement uses one of the new forms, runs each one in
Unicorn on random registers (and a memory buffer for the one-lane structure loads / stores), and writes a C program that
runs the lifted statement with the real rt_ext.h / neon.h helpers on the same inputs and compares all 32 vector
registers, the base register and the buffer with Unicorn's. Nothing of the game is kept: the words are read from main.elf.

    python test_b3.py <out.c> [trials per word]      then: clang -O1 -I ../runtime <out.c> -lm && ./a.out
"""
import random
import re
import struct
import sys

from unicorn import Uc, UC_ARCH_ARM64, UC_MODE_ARM
from unicorn.arm64_const import UC_ARM64_REG_CPACR_EL1, UC_ARM64_REG_V0, UC_ARM64_REG_X0

import recomp
from test_ext import rand_vec

M64 = (1 << 64) - 1
BUF, BUFSZ = 0x10000000, 0x1000                 # same address on both sides: the C program maps its buffer there
NEW = re.compile(r'v_i3x|v_addp|v_addsubl|v_across|v_frint|v_fcvta|v_addlp|v_sra|v_shrn|v_ielem|'
                 r'c->v\[\d+\]\.d\[0\] (?:&= ~|\|=)|c->v\[\d+\]\.d\[0\] \+ c->v')


def is_simd(w):
    return (w >> 25) & 7 == 7 or (w >> 24) & 0x3f in (0x0c, 0x0d)


def lane_ldst(w):
    """One-lane / replicate structure load-store with 2..4 registers (the [witchtime] part of the ldN decoder)."""
    return (w >> 24) & 0xbf == 0x0d and ((w >> 21) & 1 or (w >> 13) & 1)


def new_words():
    fn = recomp.Fn(recomp.BASE, recomp.BASE + recomp.TEXT_SIZE, recomp.Env())
    text = recomp.IMG[recomp.FILE_OFF:recomp.FILE_OFF + recomp.TEXT_SIZE]
    out, seen = {}, set()
    for (w,) in struct.iter_unpack('<I', text):
        if w in seen or not is_simd(w):
            continue
        seen.add(w)
        try:
            stmt = fn.lift(w, recomp.BASE + 0x1000000)
        except recomp.Unimpl:
            continue
        if NEW.search(stmt) or lane_ldst(w):
            out[w] = stmt
    return out


def run(word, v, x, mem):
    uc = Uc(UC_ARCH_ARM64, UC_MODE_ARM)
    uc.reg_write(UC_ARM64_REG_CPACR_EL1, 3 << 20)
    uc.mem_map(0x20000, 0x1000)
    uc.mem_write(0x20000, struct.pack('<I', word))
    uc.mem_map(BUF, BUFSZ)
    uc.mem_write(BUF, mem)
    for i in range(32):
        uc.reg_write(UC_ARM64_REG_V0 + i, v[i])
    for i, val in x.items():
        uc.reg_write(UC_ARM64_REG_X0 + i, val)
    uc.emu_start(0x20000, 0x20004)
    return [uc.reg_read(UC_ARM64_REG_V0 + i) for i in range(32)], {i: uc.reg_read(UC_ARM64_REG_X0 + i) for i in x}, \
        bytes(uc.mem_read(BUF, BUFSZ))


def main(path, trials):
    words = new_words()
    lines = []
    for w, stmt in sorted(words.items()):
        float_like = 'v_frint' in stmt or 'v_fcvta' in stmt
        for _ in range(trials):
            v = [rand_vec('float' if float_like else 'int') for _ in range(32)]
            rn, rm = (w >> 5) & 31, (w >> 16) & 31
            x, mem = {}, bytes(random.getrandbits(8) for _ in range(256))
            if lane_ldst(w):
                x = {rn: BUF + 64}
                if rm != 31:
                    x[rm] = random.choice([16, 32, -16])  & M64
            v2, x2, mem2 = run(w, v, x, mem + bytes(BUFSZ - len(mem)))
            sets = ''.join('c->v[%d].d[0] = 0x%xULL; c->v[%d].d[1] = 0x%xULL; ' % (i, v[i] & M64, i, v[i] >> 64) for i in range(32))
            sets += ''.join('c->x[%d] = 0x%xULL; ' % kv for kv in x.items())
            want = ', '.join('0x%xULL, 0x%xULL' % (r & M64, r >> 64) for r in v2)
            xw = ''.join('if (c->x[%d] != 0x%xULL) bad("%08x x"); ' % (i, val, w) for i, val in x2.items())
            lines.append('    { static const uint64_t want[64] = { %s }; static const uint8_t m0[256] = { %s }, m1[256] = { %s };\n'
                         '      memcpy(buf, m0, 256); %s\n      %s\n      cmpv(c, want, "%08x"); %s if (memcmp(buf, m1, 256)) bad("%08x mem"); }\n'
                         % (want, ','.join(map(str, mem)), ','.join(map(str, mem2[:256])), sets, stmt, w, xw, w))
    with open(path, 'w') as f:
        f.write('/* generated by lifter/test_b3.py from YOUR main.elf -- do not commit */\n'
                '#include <stdio.h>\n#include <string.h>\n#include <sys/mman.h>\n#include "runtime.h"\n#include "rt_ext.h"\n'
                '#undef rd8\n#undef rd16\n#undef rd32\n#undef rd64\n#undef wr8\n#undef wr16\n#undef wr32\n#undef wr64\n'
                'static int fails, cases;\nstatic void bad(const char *w) { if (fails++ < 20) printf("FAIL %s\\n", w); }\n'
                'static void cmpv(Ctx *c, const uint64_t *want, const char *w) { cases++;\n'
                '    for (int i = 0; i < 32; i++) if (c->v[i].d[0] != want[2 * i] || c->v[i].d[1] != want[2 * i + 1]) {\n'
                '        if (fails++ < 20) printf("FAIL %s v%d: got %016llx%016llx want %016llx%016llx\\n", w, i, (unsigned long long)c->v[i].d[1],\n'
                '            (unsigned long long)c->v[i].d[0], (unsigned long long)want[2 * i + 1], (unsigned long long)want[2 * i]); return; } }\n'
                'void guest_unimpl(uint64_t pc, uint32_t w, const char *why) { printf("unimpl %s\\n", why); fails++; }\n'
                'int main(void) {\n    static Ctx ctx; Ctx *c = &ctx;\n')
        f.write('    uint8_t *buf = mmap((void *)0x%xULL, 0x%x, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS | MAP_FIXED_NOREPLACE, -1, 0);\n'
                '    if (buf != (uint8_t *)0x%xULL) { puts("cannot map the test buffer"); return 2; }\n' % (BUF, BUFSZ, BUF))
        f.writelines(lines)
        f.write('    printf("%d words, %d cases, %d failures\\n", ' + str(len(words)) + ', cases, fails);\n    return fails != 0;\n}\n')
    print('%d words using the [witchtime] forms, %d cases -> %s' % (len(words), len(lines), path))


if __name__ == '__main__':
    random.seed(3)
    main(sys.argv[1], int(sys.argv[2]) if len(sys.argv) > 2 else 20)
